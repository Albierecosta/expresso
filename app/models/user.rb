class User < ApplicationRecord
  extend Enumerize

  devise :database_authenticatable, :recoverable, :rememberable, :validatable

  enumerize :role,
            in: %i[admin operator driver],
            default: :operator,
            predicates: true,
            scope: true

  validates :name, presence: true
end
